#!/usr/bin/env node
// Single source of truth for version numbers: versions.json at the repo root.
//
//   node scripts/sync-versions.mjs          write the versions into each program
//   node scripts/sync-versions.mjs --check  exit 1 if anything is out of sync
//
// Targets:
//   firmware/include/version.h   AQUAGUARD_FW_VERSION, AQUAGUARD_DATA_SCHEMA
//   mobile/package.json          version
//   mobile/app.json              expo.version, android.versionCode, ios.buildNumber
//   mobile/src/version.ts        APP_VERSION, DATA_SCHEMA
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const versions = JSON.parse(readFileSync(join(root, 'versions.json'), 'utf8'));

const semver = /^\d+\.\d+\.\d+$/;
for (const key of ['firmware', 'mobile']) {
  if (!semver.test(versions[key])) {
    console.error(`versions.json: "${key}" must look like 1.2.3`);
    process.exit(1);
  }
}
if (!Number.isInteger(versions.dataSchema) || versions.dataSchema < 1) {
  console.error('versions.json: "dataSchema" must be a positive integer');
  process.exit(1);
}

// 1.2.3 -> 10203, a monotonically increasing integer for the app stores.
const buildNumber = (v) => {
  const [major, minor, patch] = v.split('.').map(Number);
  return major * 10000 + minor * 100 + patch;
};

let stale = 0;
function put(relPath, content) {
  const path = join(root, relPath);
  let current = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {}
  if (current === content) return;
  if (check) {
    console.error(`out of sync: ${relPath}`);
    stale++;
  } else {
    writeFileSync(path, content);
    console.log(`updated ${relPath}`);
  }
}

put(
  'firmware/include/version.h',
  `// Generated by scripts/sync-versions.mjs from versions.json. Do not edit.
#pragma once

#define AQUAGUARD_FW_VERSION "${versions.firmware}"
#define AQUAGUARD_DATA_SCHEMA ${versions.dataSchema}
`,
);

put(
  'mobile/src/version.ts',
  `// Generated by scripts/sync-versions.mjs from versions.json. Do not edit.
export const APP_VERSION = '${versions.mobile}';
export const DATA_SCHEMA = ${versions.dataSchema};
`,
);

const pkgPath = 'mobile/package.json';
const pkg = JSON.parse(readFileSync(join(root, pkgPath), 'utf8'));
pkg.version = versions.mobile;
put(pkgPath, JSON.stringify(pkg, null, 2) + '\n');

const appPath = 'mobile/app.json';
const app = JSON.parse(readFileSync(join(root, appPath), 'utf8'));
app.expo.version = versions.mobile;
app.expo.android = { ...app.expo.android, versionCode: buildNumber(versions.mobile) };
app.expo.ios = { ...app.expo.ios, buildNumber: String(buildNumber(versions.mobile)) };
put(appPath, JSON.stringify(app, null, 2) + '\n');

if (check && stale) {
  console.error('Run: node scripts/sync-versions.mjs');
  process.exit(1);
}
console.log(
  `firmware ${versions.firmware} | mobile ${versions.mobile} | data schema ${versions.dataSchema}` +
    (check ? ' (in sync)' : ''),
);
